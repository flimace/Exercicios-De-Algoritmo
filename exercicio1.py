n = int(input("Digite um número inteiro: "))
soma = sum(range(1, n + 1))
print(f"A soma de 1 até {n} é {soma}")


# le o valor digitado pelo usuário.
# int() converte esse texto para um número inteiro.
# range(1, n + 1) cria uma sequência de números de 1 até \(n\).
# sum() soma todos os elementos dessa sequência.